// Browser verification: launches real Chrome, loads the game, captures every named viewpoint.
// Usage: node scripts/screenshots.mjs [url] [view1,view2,...]
import puppeteer from "puppeteer-core";
import fs from "node:fs";
import path from "node:path";

const url = process.argv[2] ?? "http://localhost:5173/";
const only = process.argv[3]?.split(",").filter(Boolean);
const outDir = process.env.SHOT_DIR ?? path.resolve("docs/screenshots");
fs.mkdirSync(outDir, { recursive: true });

const browser = await puppeteer.launch({
  executablePath: process.env.CHROME ?? "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
  headless: process.env.HEADFUL ? false : "new",
  args: ["--enable-unsafe-webgpu", "--enable-gpu", "--ignore-gpu-blocklist", "--use-angle=metal", "--window-size=1600,900"],
  defaultViewport: { width: 1600, height: 900 },
});
const page = await browser.newPage();
const logs = [];
page.on("console", (m) => { if (["error", "warn"].includes(m.type())) logs.push(`[${m.type()}] ${m.text()}`); });
page.on("pageerror", (e) => logs.push(`[pageerror] ${e.message}`));
const t0 = Date.now();
await page.goto(url, { waitUntil: "domcontentloaded" });
try {
  await page.waitForFunction(() => window.__game && document.querySelector(".loading") === null, { timeout: 120000 });
} catch {
  console.log("Timed out waiting for game. Logs:\n" + logs.join("\n"));
  await page.screenshot({ path: path.join(outDir, "_timeout.png") });
  await browser.close();
  process.exit(1);
}
const loadMs = Date.now() - t0;
const views = await page.evaluate(() => Object.keys(window.__VIEWS ?? {}));
const names = only ?? (views.length ? views : ["entrance"]);
const report = [];
for (const name of names) {
  await page.evaluate((n, m) => { window.__game.goToView(n); if (m) window.__game.setViewMode(+m); }, name, process.env.MODE ?? "");
  await new Promise((r) => setTimeout(r, 1400));
  const stats = await page.evaluate(() => {
    const g = window.__game;
    return { fps: g.engine.getFps(), draws: g["sceneInst"].drawCallsCounter.current, tris: Math.round(g.scene.getActiveIndices() / 3) };
  });
  await page.screenshot({ path: path.join(outDir, `${name}.png`) });
  report.push({ name, ...stats });
  console.log(`${name}: ${stats.fps.toFixed(0)} fps, ${stats.draws} draws, ${(stats.tris / 1000).toFixed(0)}k tris`);
}
const info = await page.evaluate(() => ({ backend: window.__game.backend, report: window.__game.assetReport(), manifest: window.__MANIFEST }));
if (!only) writeManifest(info);
fs.writeFileSync(path.join(outDir, "_report.json"), JSON.stringify({ loadMs, backend: info.backend, views: report, assets: info.report, logs }, null, 2));
console.log(`backend=${info.backend} load=${loadMs}ms`);
if (logs.length) console.log("Console:\n" + logs.slice(0, 40).join("\n"));
await browser.close();

function writeManifest(info) {
  const a = info.report;
  const lines = [
    "# Asset Manifest", "",
    "> Generated by `npm run shots` from live in-browser measurements. Do not edit the tables by hand.", "",
    `Backend at capture: **${info.backend}** · scene meshes: **${a.meshes}** · toon materials: **${a.materials}** · total vertices: **${a.totalVertices.toLocaleString()}** · UI atlas usage: **${Math.round(a.atlasUsage * 100)}%** of 2048×4096`, "",
    "## Prefab registry", "",
    "| Asset | Source | License | Textures | Materials | LOD | Collision |", "|---|---|---|---|---|---|---|",
    ...info.manifest.map((m) => `| ${m.name} | \`${m.source}\` | ${m.license} | ${m.textureSize} | ${m.materials.join(", ")} | ${m.lod} | ${m.collision} |`),
    "", "## Measured triangle budgets (per instance)", "",
    "| Prefab / section | Triangles | Instances | Total | Material families |", "|---|---:|---:|---:|---|",
    ...a.prefabs.sort((x, y) => y.tris * y.count - x.tris * x.count).map((p) => `| ${p.name} | ${p.tris.toLocaleString()} | ${p.count} | ${(p.tris * p.count).toLocaleString()} | ${p.materials.join(", ")} |`),
    "", "## Exported GLBs (`npm run assets:export`)", "",
    "Optimised with glTF Transform (`optimize --compress meshopt --palette false`) into `public/models/`; raw exports in `art-source/exported/` serve as Blender starting meshes.", "",
    ...fs.readdirSync("public/models").filter((f) => f.endsWith(".glb")).map((f) => `- \`public/models/${f}\` — ${(fs.statSync(path.join("public/models", f)).size / 1024).toFixed(0)} KB`),
    "",
  ];
  fs.writeFileSync("docs/ASSET_MANIFEST.md", lines.join("\n"));
  console.log("wrote docs/ASSET_MANIFEST.md");
}
